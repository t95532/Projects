from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import uuid
from pathlib import Path

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse

APP_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = APP_DIR / "outputs"
OUTPUT_DIR.mkdir(exist_ok=True)

app = FastAPI(title="Video Studio Local Render Engine", version="0.1.0")

# GitHub Pages frontend + local Windows engine. Restrict this further if you expose
# the engine beyond your own trusted LAN.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
)


def require_tool(name: str) -> str:
    path = shutil.which(name)
    if not path:
        raise HTTPException(
            status_code=500,
            detail=f"{name} was not found. Install FFmpeg and add it to Windows PATH.",
        )
    return path


async def save_upload(upload: UploadFile, destination: Path) -> None:
    with destination.open("wb") as out:
        shutil.copyfileobj(upload.file, out)


@app.get("/health")
def health():
    return {
        "status": "ok",
        "service": "video-studio-render-engine",
        "ffmpeg_available": shutil.which("ffmpeg") is not None,
        "ffprobe_available": shutil.which("ffprobe") is not None,
    }


@app.post("/render")
async def render_video(
    video: UploadFile = File(...),
    dubbed_audio: UploadFile = File(...),
    subtitles: UploadFile = File(...),
    accompaniment_audio: UploadFile | None = File(default=None),
    preserve_background: bool = Form(default=False),
):
    """Render a final MP4 from supplied assets.

    Important: this endpoint does not create the transcript, translation, dubbed
    voice, or separated accompaniment. Those assets must be prepared beforehand.
    For background preservation, accompaniment_audio must be a vocals-removed
    music/effects stem produced by a source-separation step.
    """
    ffmpeg = require_tool("ffmpeg")
    require_tool("ffprobe")

    if preserve_background and accompaniment_audio is None:
        raise HTTPException(
            status_code=400,
            detail="Upload a vocals-removed accompaniment track to preserve background audio.",
        )

    job_id = uuid.uuid4().hex
    work = Path(tempfile.mkdtemp(prefix=f"vs_{job_id}_"))
    source = work / "source_video"
    voice = work / "dubbed_voice.wav"
    srt = work / "translated.srt"
    bg = work / "accompaniment.wav"
    output = OUTPUT_DIR / f"video_studio_{job_id}.mp4"

    try:
        await save_upload(video, source)
        await save_upload(dubbed_audio, voice)
        await save_upload(subtitles, srt)
        if accompaniment_audio is not None:
            await save_upload(accompaniment_audio, bg)

        # FFmpeg subtitles filter requires a path-safe filename. Work directory
        # is generated by this service and contains no user-controlled path.
        subtitle_path = str(srt.resolve()).replace("\\", "/").replace(":", r"\:")
        video_filter = f"subtitles='{subtitle_path}'"

        if preserve_background:
            audio_filter = (
                "[1:a]aresample=48000,volume=1.0[voice];"
                "[2:a]aresample=48000,volume=0.75[bg];"
                "[voice][bg]amix=inputs=2:duration=longest:dropout_transition=2,"
                "alimiter=limit=0.95[aout]"
            )
            command = [
                ffmpeg, "-y", "-i", str(source), "-i", str(voice), "-i", str(bg),
                "-filter_complex", audio_filter,
                "-vf", video_filter, "-map", "0:v:0", "-map", "[aout]",
                "-c:v", "libx264", "-preset", "medium", "-crf", "20",
                "-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart",
                "-shortest", str(output),
            ]
        else:
            command = [
                ffmpeg, "-y", "-i", str(source), "-i", str(voice),
                "-vf", video_filter, "-map", "0:v:0", "-map", "1:a:0",
                "-c:v", "libx264", "-preset", "medium", "-crf", "20",
                "-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart",
                "-shortest", str(output),
            ]

        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode != 0 or not output.exists():
            tail = (result.stderr or result.stdout)[-3500:]
            raise HTTPException(status_code=500, detail=f"FFmpeg render failed: {tail}")

        return FileResponse(
            output,
            media_type="video/mp4",
            filename="VideoStudio_Translated.mp4",
            background=None,
        )
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    import uvicorn
    uvicorn.run("server:app", host="0.0.0.0", port=8765, reload=False)
